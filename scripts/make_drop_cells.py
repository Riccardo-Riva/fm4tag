"""Write the final dropout cells: the sweep's batch sizes and the time estimates they imply.

Reads ``results.csv`` of ``scripts/dropout_batch_sweep.py`` (one row per arm, measured on its first pretraining
seed) and copies ``D_drop.cells`` with, per cell, ``datamodule.batch_size`` replaced by the arm's accepted size
and ``@est`` (seconds per epoch on the slowest card) = the previous estimate divided by the measured throughput
ratio (jets/s with dropout at the new size over jets/s without dropout at the old size), plus 10%.  The learning
rates are NOT changed.  Exits non-zero, writing nothing, if an arm has no accepted batch size or a usable ratio.

    python scripts/make_drop_cells.py --cells scripts/configs/campaign/D_drop.cells \
        --sweep <sweep dir>/results.csv --out scripts/configs/campaign/D_drop_final.cells
"""

from __future__ import annotations

import argparse
import math
import re
import sys
from pathlib import Path

import pandas as pd

DEFAULT_EST = 1250  # EST_SECONDS_PER_EPOCH of the pretrained-arm launch in the D_drop.cells header
MARGIN = 1.10


def arm_of(cell: str) -> str:
    """``ftjc_p1s424_d02`` -> ``ftjc_p1``; ``sc_d02`` -> ``sc``; ``scjc_clip1_d02`` -> ``scjc_clip1``."""
    return re.sub(r's\d+$', '', cell.removesuffix('_d02'))


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument('--cells', type=Path, required=True)
    parser.add_argument(
        '--sweep', type=Path, required=True, help='results.csv of the sweep'
    )
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()

    sweep = pd.read_csv(args.sweep)
    by_arm = {arm_of(row['cell']): row for _, row in sweep.iterrows()}
    lines_out, header, problems = [], [], []
    for line in args.cells.read_text().splitlines():
        if not line.strip() or line.startswith('#'):
            header.append(line)
            continue
        name, *tokens = line.split()
        arm = arm_of(name)
        row = by_arm.get(arm)
        if row is None:
            problems.append(f'{name}: no row of arm {arm} in the sweep')
            continue
        batch, ratio = row.get('batch_dropout'), row.get('jets_per_s_ratio')
        if pd.isna(batch) or pd.isna(ratio) or not math.isfinite(ratio) or ratio <= 0:
            problems.append(
                f'{name}: sweep has batch_dropout={batch}, jets_per_s_ratio={ratio}'
            )
            continue
        est_old = next(
            (int(t.removeprefix('@est=')) for t in tokens if t.startswith('@est=')),
            DEFAULT_EST,
        )
        est_new = int(round(est_old / ratio * MARGIN, -1))
        kept = [t for t in tokens if not t.startswith('@est=')]
        kept = [
            f'datamodule.batch_size={int(batch)}'
            if t.startswith('datamodule.batch_size=')
            else t
            for t in kept
        ]
        lines_out.append(f'{name}  {" ".join(kept)} @est={est_new}')
    if problems:
        sys.exit('NOT written:\n  ' + '\n  '.join(problems))
    note = [
        f'# GENERATED by scripts/make_drop_cells.py from {args.cells.name} and {args.sweep}:',
        '# batch sizes = the largest that fit with dropout (sweep peak <= 41 GiB), learning rates unchanged,',
        '# @est = previous estimate / measured throughput ratio + 10%.',
        '#',
    ]
    args.out.write_text('\n'.join(note + header + lines_out) + '\n')
    print(f'wrote {args.out}')
    for ln in lines_out:
        toks = ln.split()
        print(
            toks[0],
            next(t for t in toks if t.startswith('datamodule.batch_size=')),
            toks[-1],
        )


if __name__ == '__main__':
    main()
